const has = (v) => v !== undefined && v !== null && v !== '' && !Number.isNaN(Number(v));
const yearsText = (v) => (Number(v) === 1 ? t('year1') : t('years', { n: smart(Number(v)) }));
const hasBattery = (p) => Number(p.storageKwh) > 0;
const projectName = (p) => (lang === 'es' ? p.name_es || p.name_ca : p.name_ca || p.name_es) || '';
const projectDescription = (p) => (lang === 'es' ? p.description_es || p.description_ca : p.description_ca || p.description_es) || '';

const matches = (p, filter) =>
    filter === 'all' ||
    (filter === 'baterias' ? hasBattery(p) : p.type === filter);

// YouTube link → video id (youtu.be/ID, youtube.com/watch?v=ID, /shorts/ID, /embed/ID)
const youtubeId = (url) => {
    const m = String(url).match(/(?:youtu\.be\/|youtube(?:-nocookie)?\.com\/(?:watch\?(?:.*&)?v=|shorts\/|embed\/|live\/))([\w-]{11})/);
    return m ? m[1] : null;
};

const mediaItems = (p) => [
    ...(p.photos || []).filter(Boolean).map(src => ({ type: 'image', src })),
    ...(p.videos || []).map(youtubeId).filter(Boolean).map(id => ({ type: 'youtube', id })),
];

const mediaItemHtml = (m, name, n) => {
    if (m.type === 'youtube') {
        // Lightweight placeholder: the YouTube player is only loaded when the visitor clicks play.
        return `<button type="button" class="yt" data-yt="${esc(m.id)}" aria-label="${esc(t('playVideo', { name }))}">
                    <img src="https://i.ytimg.com/vi/${esc(m.id)}/hqdefault.jpg" alt="" loading="lazy">
                    <span class="yt-play" aria-hidden="true"></span>
                </button>`;
    }
    return `<img src="${esc(m.src)}" alt="${esc(t('photoAlt', { name, n }))}" loading="lazy">`;
};

const mediaHtml = (p, name) => {
    const items = mediaItems(p);
    if (!items.length) {
        return `<svg viewBox="0 0 320 180" role="img" aria-label="${esc(t('altIllustration', { name }))}"><use href="#ill-${esc(p.illustration || 'house')}"></use></svg>`;
    }
    if (items.length === 1) return mediaItemHtml(items[0], name, 1);
    const slides = items.map((m, i) =>
        `<div class="slide${i === 0 ? ' is-active' : ''}" ${i === 0 ? '' : 'aria-hidden="true" inert'}>${mediaItemHtml(m, name, i + 1)}</div>`).join('');
    const dots = items.map((_, i) => `<i class="${i === 0 ? 'is-active' : ''}"></i>`).join('');
    return `
        <div class="slider" data-index="0">
            ${slides}
            <button type="button" class="slider-btn prev" data-dir="-1" aria-label="${esc(t('prevPhoto'))}">‹</button>
            <button type="button" class="slider-btn next" data-dir="1" aria-label="${esc(t('nextPhoto'))}">›</button>
            <span class="slider-dots" aria-hidden="true">${dots}</span>
        </div>`;
};

document.addEventListener('click', (e) => {
    // Load the YouTube player on demand
    const yt = e.target.closest('.yt');
    if (yt) {
        const iframe = document.createElement('iframe');
        iframe.src = `https://www.youtube-nocookie.com/embed/${yt.dataset.yt}?autoplay=1&rel=0`;
        iframe.title = yt.getAttribute('aria-label');
        iframe.allow = 'accelerometer; autoplay; encrypted-media; gyroscope; picture-in-picture; fullscreen';
        iframe.allowFullscreen = true;
        yt.replaceWith(iframe);
        return;
    }
    // Slider navigation (event delegation, works after re-rendering)
    const btn = e.target.closest('.slider-btn');
    if (!btn) return;
    const slider = btn.closest('.slider');
    const slides = slider.querySelectorAll('.slide');
    const dots = slider.querySelectorAll('.slider-dots i');
    const next = (Number(slider.dataset.index) + Number(btn.dataset.dir) + slides.length) % slides.length;
    slider.dataset.index = next;
    slides.forEach((s, i) => {
        const active = i === next;
        s.classList.toggle('is-active', active);
        s.toggleAttribute('inert', !active);
        if (active) s.removeAttribute('aria-hidden'); else s.setAttribute('aria-hidden', 'true');
        // Stop a playing video when leaving its slide
        const iframe = s.querySelector('iframe');
        if (iframe && !active) iframe.src = iframe.src.replace('autoplay=1', 'autoplay=0');
    });
    dots.forEach((d, i) => d.classList.toggle('is-active', i === next));
});

const projectHtml = (p, i) => {
    const name = projectName(p);
    const description = projectDescription(p);
    const battery = hasBattery(p);
    const sky = ['media-day', 'media-warm', 'media-dusk'][i % 3];
    const kw = (v) => (Number(v) > 0 ? `${smart(Number(v))} kW` : t('no'));
    const loads = (p.loads || []).filter(l => l && l.key).map(l =>
        `<li>${esc(t('load_' + l.key))}${l.detail ? ` <span>${esc(l.detail)}</span>` : ''}</li>`).join('');

    const eq = p.equipment || {};
    const equipment = ['panels', 'inverter', 'battery'].filter(k => eq[k]).map(k => [k, localized(eq[k])]);
    const equipmentHtml = equipment.length ? `
            <div class="project-equip">
                <p>${esc(t('equipment'))}</p>
                <ul>${equipment.map(([k, v]) =>
                    `<li><span>${esc(t('equip_' + k))}</span><strong>${esc(v)}</strong></li>`).join('')}</ul>
            </div>` : '';

    const kpis = [
        has(p.panelsKwp) && [t('kpiPower'), `${smart(Number(p.panelsKwp))} kWp`],
        has(p.productionKwh) && [t('kpiProduction'), `${num(p.productionKwh)} kWh<small>${esc(t('perYear'))}</small>`],
        has(p.paybackYears) && [t('kpiPayback'), esc(yearsText(p.paybackYears))],
        has(p.costEur) && [t('kpiCost'), `${num(p.costEur)} €`],
    ].filter(Boolean).map(([k, v]) => `<div><dt>${esc(k)}</dt><dd>${v}</dd></div>`).join('');

    const rows = [
        [t('specType'), `${t('type_' + p.type)}${battery ? ` ${t('withBattery')}` : ''}`],
        has(p.panelsKwp) && [t('specPanelsKwp'), `${smart(Number(p.panelsKwp))} kWp`],
        has(p.panels) && [t('specPanels'), num(p.panels)],
        [t('specOptimizers'), p.optimizers ? t('yes') : t('no')],
        [t('specInverter'), kw(p.inverterKw)],
        [t('specMicro'), kw(p.microinverterKw)],
        [t('specStorage'), battery ? `${smart(Number(p.storageKwh))} kWh` : t('no')],
        battery && has(p.batteries) && [t('specBatteries'), num(p.batteries)],
        has(p.consumptionKwh) && [t('specConsumption'), `${num(p.consumptionKwh)} kWh`],
        has(p.productionKwh) && [t('specProduction'), `${num(p.productionKwh)} kWh`],
        has(p.paybackYears) && [t('specPayback'), yearsText(p.paybackYears)],
        has(p.costEur) && [t('specCost'), `${num(p.costEur)} €`],
        ...equipment.map(([k, v]) => [t('equip_' + k), v]),
    ].filter(Boolean).map(([k, v]) => `<tr><th scope="row">${esc(k)}</th><td>${esc(v)}</td></tr>`).join('');

    const meta = [
        esc(p.location || ''),
        has(p.panels) && esc(t('panelsN', { n: num(p.panels) })),
        battery && `${esc(smart(Number(p.storageKwh)))} kWh`,
    ].filter(Boolean).join(' · ');

    return `
    <article class="project${p.example ? ' is-example' : ''}" ${matches(p, currentFilter) ? '' : 'hidden'}>
        <div class="project-media ${sky}">
            ${mediaHtml(p, name)}
            <span class="badge">${esc(t('type_' + p.type))}${battery ? ` ${esc(t('withBattery'))}` : ''}</span>
            ${p.example ? `<span class="tag-example">${esc(t('example'))}</span>` : ''}
        </div>
        <div class="project-body">
            <h3>${esc(name)}</h3>
            <p class="project-meta">
                <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" aria-hidden="true"><path d="M20 10c0 6-8 12-8 12s-8-6-8-12a8 8 0 0 1 16 0Z"></path><circle cx="12" cy="10" r="3"></circle></svg>
                ${meta}
            </p>
            ${description ? `<p class="project-desc">${esc(description)}</p>` : ''}
            ${kpis ? `<dl class="project-kpis">${kpis}</dl>` : ''}
            ${equipmentHtml}
            ${has(p.consumptionKwh) || loads ? `
            <div class="project-loads">
                ${has(p.consumptionKwh) ? `<p><span>${esc(t('consumption'))}</span> <strong>${num(p.consumptionKwh)} kWh</strong></p>` : ''}
                ${loads ? `<ul>${loads}</ul>` : ''}
            </div>` : ''}
            <details class="project-spec">
                <summary>${esc(t('spec'))}</summary>
                <table><tbody>${rows}</tbody></table>
            </details>
            ${p.document ? `<a class="project-doc" href="${esc(p.document)}" target="_blank" rel="noopener">${esc(t('document'))}</a>` : ''}
        </div>
    </article>`;
};

const renderProjects = () => {
    projectsEl.innerHTML = PROJECTS.map(projectHtml).join('');
    emptyNote.hidden = PROJECTS.some(p => matches(p, currentFilter));
    observeReveal(projectsEl.querySelectorAll('.project'));
};

const renderTotals = () => {
    const sum = (k) => PROJECTS.reduce((a, p) => a + (Number(p[k]) || 0), 0);
    const totals = {
        count: num(PROJECTS.length),
        kwp: smart(Math.round(sum('panelsKwp') * 10) / 10),
        storage: smart(Math.round(sum('storageKwh') * 10) / 10),
        mwh: smart(Math.round(sum('productionKwh') / 100) / 10),
    };
    document.querySelectorAll('[data-total]').forEach(el => { el.textContent = totals[el.dataset.total]; });
};

