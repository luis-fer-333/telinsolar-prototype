// ===== Reveal on scroll =====
const io = new IntersectionObserver((entries) => {
    entries.forEach((entry, i) => {
        if (entry.isIntersecting) {
            entry.target.style.transitionDelay = `${(i % 3) * 80}ms`;
            entry.target.classList.add('visible');
            io.unobserve(entry.target);
        }
    });
}, { threshold: 0.12 });
function observeReveal(els) {
    els.forEach(el => {
        if (el.classList.contains('visible')) return;
        el.classList.add('reveal');
        io.observe(el);
    });
}
observeReveal(document.querySelectorAll(
    '.card, .projects-totals, .tl-step, .payplan, .section-head, .prox-content, .prox-visual, .benefits-content, .benefits-visual, .cta-form, .cta-text'
));

// ===== Animated counters =====
const countObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (!entry.isIntersecting) return;
        const el = entry.target;
        const target = parseInt(el.dataset.count, 10);
        const suffix = el.dataset.suffix || '';
        const startTime = performance.now();
        const tick = (now) => {
            const p = Math.min((now - startTime) / 1400, 1);
            el.textContent = Math.round((1 - Math.pow(1 - p, 3)) * target) + suffix;
            if (p < 1) requestAnimationFrame(tick);
        };
        requestAnimationFrame(tick);
        countObserver.unobserve(el);
    });
}, { threshold: 0.5 });
document.querySelectorAll('.num[data-count]').forEach(c => countObserver.observe(c));

// ===== Contact form =====
// Sends to the service configured in config.js (Formspree or Web3Forms). With no endpoint it runs in demo mode.
const form = document.getElementById('contactForm');
const formNote = document.getElementById('formNote');
const formConfig = (window.TELINSOLAR_CONFIG && window.TELINSOLAR_CONFIG.form) || {};
const field = (n) => form.elements.namedItem(n);
const showNote = (msg, ok) => { formNote.textContent = msg; formNote.className = `form-note ${ok ? 'ok' : 'err'}`; };

form.addEventListener('submit', async (e) => {
    e.preventDefault();
    const values = Object.fromEntries(['name', 'phone', 'address', 'email', 'type', 'message']
        .map(n => [n, field(n).value.trim()]));
    const phoneDigits = values.phone.replace(/\D/g, '');

    ['name', 'phone', 'address', 'email'].forEach(n => field(n).removeAttribute('aria-invalid'));
    const missing = [];
    if (!values.name) missing.push('name');
    if (phoneDigits.length < 9) missing.push('phone');
    if (!values.address) missing.push('address');
    if (missing.length) {
        missing.forEach(n => field(n).setAttribute('aria-invalid', 'true'));
        field(missing[0]).focus();
        return showNote(t('formError'), false);
    }
    if (values.email && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(values.email)) {
        field('email').setAttribute('aria-invalid', 'true');
        field('email').focus();
        return showNote(t('formEmailError'), false);
    }

    // Honeypot: real people never fill this hidden field
    if (field('botcheck').checked) { form.reset(); return showNote(t('formOk'), true); }

    if (!formConfig.endpoint) {
        console.warn('Formulario en modo demostración: configura el endpoint en config.js');
        form.reset();
        return showNote(t('formOk'), true);
    }

    const submit = form.querySelector('button[type="submit"]');
    const label = submit.textContent;
    submit.disabled = true;
    submit.textContent = t('formSending');
    const typeLabel = field('type').selectedOptions[0]?.textContent || values.type;
    try {
        const res = await fetch(formConfig.endpoint, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
            body: JSON.stringify({
                ...(formConfig.accessKey ? { access_key: formConfig.accessKey } : {}),
                subject: `Nova sol·licitud web — ${values.name}`,   // Web3Forms
                _subject: `Nova sol·licitud web — ${values.name}`,  // Formspree
                from_name: 'Web TELinSOLAR',
                Nom: values.name,
                'Telèfon': values.phone,
                'Adreça': values.address,
                email: values.email || undefined,
                'Tipus': typeLabel,
                Necessitats: values.message,
                Idioma: lang.toUpperCase(),
            }),
        });
        if (!res.ok) throw new Error(`HTTP ${res.status}`);
        form.reset();
        showNote(t('formOk'), true);
    } catch (err) {
        console.error('Error enviando el formulario', err);
        showNote(t('formSendError'), false);
    } finally {
        submit.disabled = false;
        submit.textContent = label;
    }
});

